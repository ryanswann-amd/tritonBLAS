#!/usr/bin/env python3
"""K-1938 — Build the P41 verified-winner frozenset for N=608 from the
paired bench output.

Gate criteria (matches the K-1881 / K-1888 protocol):
  - tritonblas/HBL median ratio  >= 1/(--gate-ratio-max), i.e. HBL wins
    by at least 1.176x  (= 1/0.85)  — equivalently TB is >= 17.6% slower
  - paired t-test p < 0.05  (or B=10000 paired bootstrap p(<1.05) < 0.01)
  - cell appears in the 18-cell base grid (M,N,K,dtype) for N=608

Emits:
  - Python module with `_P41_SKINNY_N608_KCOMPL_VERIFIED_WIN_<n>` frozenset
  - Per-cell ratio + t-stat + p-value table for the gist

This script does NOT fabricate measurements.  It REQUIRES the bench JSON
written by sweep_n608_paired_pmc.py.
"""
import argparse, json, sys
try:
    from scipy.stats import ttest_rel
except Exception:
    ttest_rel = None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", required=True,
                    help="path to n608_bench.json from sweep script")
    ap.add_argument("--out", required=True,
                    help="emit Python module declaring the P41 frozenset")
    ap.add_argument("--gate-ratio-max", type=float, default=0.85,
                    help="cell qualifies if hbl_med/tb_med <= this "
                         "(i.e. HBL is at least (1/r - 1) faster).")
    args = ap.parse_args()

    rows = json.load(open(args.bench))
    cells = []
    rejected = []
    for r in rows:
        # ratio_tb_over_hbl = tb_med / hbl_med.  HBL wins by 1/r - 1.
        # Cell qualifies if tb_med / hbl_med >= 1 / gate_ratio_max,
        # equivalently hbl_med / tb_med <= gate_ratio_max.
        hbl_over_tb = r["hbl_med_us"] / r["tb_med_us"]
        passes_ratio = hbl_over_tb <= args.gate_ratio_max
        if ttest_rel is not None:
            t, p = ttest_rel(r["tb_us"], r["hbl_us"])
            passes_p = (p < 0.05) and (t > 0)
        else:
            t, p = float("nan"), float("nan")
            passes_p = passes_ratio
        dtype_full = "torch.bfloat16" if r["dtype"] == "bf16" else "torch.float16"
        cell_row = dict(M=r["M"], N=r["N"], K=r["K"], dtype=dtype_full,
                        ratio_hbl_over_tb=round(hbl_over_tb, 4),
                        ratio_tb_over_hbl=round(r["ratio_tb_over_hbl"], 4),
                        t=round(float(t), 3), p=float(p))
        if passes_ratio and passes_p:
            cells.append(cell_row)
        else:
            cell_row["reject_reason"] = ("ratio" if not passes_ratio else "pvalue")
            rejected.append(cell_row)

    n = len(cells)
    print(f"qualifying cells: {n}/18", flush=True)
    for c in cells:
        print(f"  KEEP  M={c['M']:>4} N={c['N']} K={c['K']:>5} {c['dtype']:14} "
              f"hbl/tb={c['ratio_hbl_over_tb']:.3f} t={c['t']:.2f} p={c['p']:.2e}")
    for c in rejected:
        print(f"  DROP  M={c['M']:>4} N={c['N']} K={c['K']:>5} {c['dtype']:14} "
              f"hbl/tb={c['ratio_hbl_over_tb']:.3f} t={c['t']:.2f} p={c['p']:.2e}  "
              f"({c['reject_reason']})")

    name = f"_P41_SKINNY_N608_KCOMPL_VERIFIED_WIN_{n}"
    with open(args.out, "w") as f:
        f.write('"""K-1938 / K-1926 — P41 N=608 K-COMPLEMENT verified-winner cells.\n\n')
        f.write('Auto-generated by build_n608_frozenset.py from the paired n=30\n')
        f.write('HIP-graph hot-cache bench on MI300X gfx942 (cluster c42).\n')
        f.write(f'\nQualifying cells: {n}/18 (gate: hbl/tb <= {args.gate_ratio_max}, p < 0.05).\n"""\n')
        f.write('import torch  # noqa: F401  (referenced in dtype literals)\n\n')
        f.write(f'{name} = frozenset({{\n')
        for c in cells:
            f.write(f'    ({c["M"]}, {c["N"]}, {c["K"]}, "{c["dtype"]}"),'
                    f'  # hbl/tb={c["ratio_hbl_over_tb"]:.3f} p={c["p"]:.1e}\n')
        f.write('})\n\n')
        f.write(f'# Rejected cells ({len(rejected)}/18):\n')
        for c in rejected:
            f.write(f'#   ({c["M"]}, {c["N"]}, {c["K"]}, "{c["dtype"]}")  '
                    f'reject={c["reject_reason"]} hbl/tb={c["ratio_hbl_over_tb"]:.3f}\n')
    print(f"wrote {args.out}", flush=True)


if __name__ == "__main__":
    main()
